#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Language {
    En,
    ZhCn,
}

impl Language {
    pub fn detect() -> Self {
        let locale = sys_locale::get_locale().unwrap_or_default().to_lowercase();
        if locale.starts_with("zh") {
            Self::ZhCn
        } else {
            Self::En
        }
    }

    pub fn short_label(self) -> &'static str {
        match self {
            Self::En => "EN",
            Self::ZhCn => "简中",
        }
    }
}

